from __future__ import annotations

import json
import sqlite3
from datetime import datetime, timezone

from echo.compare import field_mismatches
from echo.notify.service import emit_activity, emit_notification


def _utcnow() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def assess_integrity(
    finance: sqlite3.Connection,
    analytics: sqlite3.Connection,
    echo: sqlite3.Connection,
    *,
    run_id: str,
) -> dict:
    mismatches = field_mismatches(finance, analytics)
    count = len(mismatches)
    sample = [row["record_id"] for row in mismatches[:5]]
    integrity = "corrupted" if count else "healthy"
    echo.execute(
        "UPDATE sync_runs SET integrity_status=? WHERE id=? AND integrity_status IN ('pending','unknown')",
        (integrity, run_id),
    )
    echo.commit()
    return {
        "run_id": run_id,
        "integrity_status": integrity,
        "amount_discrepancy_count": count,
        "discrepancy_count": count,
        "sample_record_ids": sample,
        "affected_record_ids": sample,
        "fields": sorted({row.get("field") for row in mismatches if row.get("field")}),
    }


def create_incident_from_monitor(
    echo: sqlite3.Connection,
    *,
    run_id: str,
    pipeline_id: str,
    findings: dict,
    incident_id: str,
    case_id: str | None = None,
) -> str:
    discrepancy_count = int(findings.get("discrepancy_count", 0) or 0)
    alert = {
        "schema_version": "1.0",
        "incident_id": incident_id,
        "pipeline_id": pipeline_id,
        "run_id": run_id,
        "detected_at": _utcnow(),
        "severity": "high" if discrepancy_count else "low",
        "execution_status": "succeeded",
        "integrity_status": findings["integrity_status"],
        "monitor_findings": {
            "amount_discrepancy_count": findings.get("amount_discrepancy_count", discrepancy_count),
            "amount_discrepancy_sample_record_ids": findings.get("sample_record_ids", []),
            "discrepancy_count": discrepancy_count,
            "affected_record_ids": findings.get("affected_record_ids", findings.get("sample_record_ids", [])),
            "fields": findings.get("fields", []),
            "alert_rule": "source_destination_integrity",
        },
        "message": "Source and destination integrity check failed after successful synchronization."
        if findings["integrity_status"] == "corrupted"
        else "Integrity check passed.",
    }
    echo.execute(
        """
        INSERT INTO incidents(id, run_id, pipeline_id, severity, detected_at, alert_json, investigation_status, recovery_status)
        VALUES (?,?,?,?,?,?, 'pending', 'pending')
        """,
        (incident_id, run_id, pipeline_id, alert["severity"], alert["detected_at"], json.dumps(alert)),
    )
    now = _utcnow()
    echo.execute(
        "INSERT INTO jobs(incident_id, job_type, status, attempts, created_at, updated_at) VALUES (?,?, 'queued', 0, ?, ?)",
        (incident_id, "investigate", now, now),
    )
    emit_activity(echo, "integrity_alert", "Integrity incident generated by monitor", incident_id=incident_id, run_id=run_id)
    emit_notification(
        echo,
        incident_id=incident_id,
        pipeline_id=pipeline_id,
        severity=alert["severity"],
        status="detected",
        summary=alert["message"],
    )
    echo.commit()
    if case_id:
        echo.execute("UPDATE incidents SET case_id=? WHERE id=?", (case_id, incident_id))
        echo.execute("UPDATE sync_runs SET incident_id=? WHERE id=?", (incident_id, run_id))
        echo.commit()
    return incident_id
